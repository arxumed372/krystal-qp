// Настройки и память расширения.
//
// Хранится ДВЕ вещи: заготовки сумм и ширин диапазона, и выученные поля.
// Выученные поля привязаны к домену, а не к конкретному пулу — разметка
// страницы у всех пулов одна.
window.KQPSettings = (() => {
  const KEY = 'krystal-qp';

  const DEFAULTS = {
    // Суммы в долларах. Владелец жал одни и те же значения руками —
    // теперь они кнопками.
    amounts: [50, 100, 250, 500],
    // Ширина диапазона в процентах ОТ ТЕКУЩЕЙ ЦЕНЫ, в обе стороны.
    widths: [5, 10, 25, 50],
    // Последнее выбранное, чтобы не тыкать заново.
    lastAmount: 100,
    lastWidth: 5,
    // Форма диапазона:
    //   'both' — симметрично вокруг цены, нужны оба токена;
    //   'down' — только вниз, верх упирается в текущую цену. Позиция целиком
    //            ниже рынка, поэтому заходит ОДНОЙ котируемой монетой и
    //            «пустой верхней части» не возникает;
    //   'up'   — только вверх, заходит одним торгуемым токеном.
    lastShape: 'down',
    // Отступ верхней границы вниз от цены, в процентах. У владельца на снимке
    // верх стоит на 3.9% ниже цены — ровно в цену ставить нельзя, остаётся
    // полоска, где второй токен всё ещё требуется.
    gaps: [1, 3, 5, 10],
    lastGap: 3,
    // Выученные поля: {amount:{...}, minPrice:{...}, maxPrice:{...}}
    fields: null,
    // Пауза между вводом полей: приложение пересчитывает диапазон, и если
    // писать подряд без ожидания, второе значение затирается первым.
    settleMs: 700,
  };

  async function load() {
    return new Promise(res => {
      try {
        chrome.storage.local.get(KEY, (o) => {
          res({ ...DEFAULTS, ...((o && o[KEY]) || {}) });
        });
      } catch (e) {
        res({ ...DEFAULTS });
      }
    });
  }

  async function save(patch) {
    const cur = await load();
    const next = { ...cur, ...patch };
    return new Promise(res => {
      try {
        chrome.storage.local.set({ [KEY]: next }, () => res(next));
      } catch (e) {
        res(next);
      }
    });
  }

  return { load, save, DEFAULTS };
})();
